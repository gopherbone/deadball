"""DEADBALL asset pipeline: regenerate everything in playdate/source/images + fonts.

  python3 tools/assets/build.py                 # all steps
  python3 tools/assets/build.py faces parks     # only some steps
  python3 tools/assets/build.py --fetch         # also (re)query LoC + download missing photos first

Steps: fonts, ui, cards, crowd, parks, faces, pack, readme. Faces need the cached downloads in
tools/assets/.cache/loc (run faces_fetch.py once) and the checked-in faces_detect.json.
`pack` (pack.py) packs the loose faces / archive photos / fixtures into the few imagetables and
JSON blobs the .pdx actually ships (-> playdate/build/packed); `make` in playdate/ re-runs it
whenever those inputs change, so it's here only to check packing right after a rebuild.

Puppets are NOT in the default run: the BallCast puppets are prerendered from the humanoid mesh
(tools/assets/humanoid/build.py, needs blender). `build.py puppets` runs that pipeline; the old
hand-drawn generator (tools/assets/puppets.py) is retired -- running it would overwrite the
humanoid sprites and the README part.
"""
import os, subprocess, sys, time, glob, importlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import README_PARTS, IMAGES, ROOT

STEPS = ["fonts", "ui", "cards", "crowd", "parks", "faces", "pack"]  # crowd before parks (parks samples crowd tiles)
MODULES = {"crowd": "crowd", "fonts": "fonts", "ui": "ui_art", "cards": "cards", "parks": "parks",
           "faces": "faces_build", "pack": "pack"}
HUMANOID = os.path.join(os.path.dirname(os.path.abspath(__file__)), "humanoid", "build.py")


def assemble_readme():
    parts = sorted(glob.glob(os.path.join(README_PARTS, "*.md")))
    body = "\n".join(open(p).read().rstrip() + "\n" for p in parts)
    total = 0
    for dp, _, fns in os.walk(IMAGES):
        if os.sep + "archive" in dp:
            continue  # images/archive is owned by the archive agent
        for f in fns:
            total += os.path.getsize(os.path.join(dp, f))
    head = f"""# DEADBALL images & fonts

GENERATED by `tools/assets/build.py` (assets agent) -- don't hand-edit files in `images/` or `fonts/`;
change the pipeline in `tools/assets/` and re-run it. Sources are in `tools/assets/readme/*.md`.

Conventions
- Paths below are relative to `playdate/source/`; load without the `.png` extension, e.g.
  `gfx.image.new("images/ui/icons/mail")`.
- Everything is 1-bit. Opaque images are black/white PNGs. Sprites/icons that need transparency are
  grayscale+alpha PNGs (alpha 0 = transparent) -- draw them with the normal draw mode.
- **Imagetables** are matrix tables named `<name>-table-<w>-<h>.png`; load as
  `gfx.imagetable.new("images/.../<name>")`. Frames are numbered row-major (left->right, top->bottom)
  and `getImage(n)` is **1-based**. Frame orders are listed per table below.
- Total size of `images/` (excluding `images/archive/`, which the archive agent documents): {total / 1e6:.1f} MB.
"""
    out = os.path.join(IMAGES, "README.md")
    with open(out, "w") as fh:
        fh.write(head + "\n" + body)
    return out


def main(argv):
    if "--fetch" in argv:
        import faces_fetch, faces_select
        idx = faces_fetch.search_all()
        faces_fetch.download(idx, set(faces_select.prefilter(idx)))
    steps = [a for a in argv if not a.startswith("--")] or STEPS + ["readme"]
    for s in steps:
        if s == "readme":
            continue
        t = time.time()
        if s == "puppets":
            # humanoid pipeline (blender): sprites + anim_tracks.json; readme/20-puppets.md is hand-kept
            subprocess.run([sys.executable, HUMANOID], check=True)
            print(f"[{s}] {time.time() - t:.1f}s")
            continue
        mod = importlib.import_module(MODULES[s])
        mod.build()
        print(f"[{s}] {time.time() - t:.1f}s")
    print("README:", assemble_readme())


if __name__ == "__main__":
    main(sys.argv[1:])
